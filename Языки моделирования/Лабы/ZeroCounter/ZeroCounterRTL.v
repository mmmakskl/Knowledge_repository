`timescale 1ns/1ps

module ZeroCounterRTL (
    input         clk,        // ???????? ??????
    input         reset,      // ?????????? ????? (??????? ??? «1»)
    input         in,         // ??????? ???: 0 ? ???????, 1 ? ????????????? ????
    output [31:0] zero_count  // ?????: ??????? ??????? ?????
);

  // ???????? ?????????
  reg [31:0] count_reg;
  reg        running;

  // ??????? ??? ?????????? ?????????? ?????????
  wire [31:0] next_count;
  wire        next_running;

  // ????????????? ??????: ????????????, ????? ????? ????????? ?? ????????? ?????
  assign next_count = reset
                      ? 32'd0
                      : (running
                          ? (in ? count_reg       // ????????? «1»: ????????? ??????? ????????
                                 : count_reg + 1) // «0»: ??????????? ????
                          : count_reg);         // ??? ???????????: ?? ????????
  assign next_running = reset
                        ? 1'b1
                        : (running
                            ? (in ? 1'b0    // «1»: ????????? ? stopped
                                   : 1'b1)  // «0»: ???????? ? running
                            : running);    // ???? ??? stopped: ?? ????????

  // ???????????????? ??????: ?? ?????? ?????? clk ????????? ????????
  always @(posedge clk) begin
    if (reset) begin
      count_reg <= 32'd0;
      running   <= 1'b1;
    end else begin
      count_reg <= next_count;
      running   <= next_running;
    end
  end

  // ????? ???????? ?????????? ???????? ????????
  assign zero_count = count_reg;

endmodule
